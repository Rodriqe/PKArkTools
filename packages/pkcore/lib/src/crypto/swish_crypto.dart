import 'dart:typed_data';

import 'package:crypto/crypto.dart';

import '../util/bytes.dart';
import 'sc_block.dart';

/// SwishCrypto ("MemeCrypto V2"): cifrado de los saves de Espada/Escudo,
/// Leyendas Arceus, Escarlata/Púrpura y Leyendas Z-A.
///
/// El archivo es una secuencia de [SCBlock] serializados, cifrada con un
/// xorpad estático de 0x7F bytes y terminada en un SHA-256 de 0x20 bytes
/// calculado sobre `intro + payload cifrado + outro`.
///
/// Portado de PKHeX.Core `SwishCrypto.cs` (GPL-3.0).
abstract final class SwishCrypto {
  static const int hashSize = 0x20;

  static final Uint8List _intro = Uint8List.fromList(const [
    0x9E, 0xC9, 0x9C, 0xD7, 0x0E, 0xD3, 0x3C, 0x44, 0xFB, 0x93, 0x03, 0xDC, 0xEB, 0x39, 0xB4, 0x2A, //
    0x19, 0x47, 0xE9, 0x63, 0x4B, 0xA2, 0x33, 0x44, 0x16, 0xBF, 0x82, 0xA2, 0xBA, 0x63, 0x55, 0xB6, //
    0x3D, 0x9D, 0xF2, 0x4B, 0x5F, 0x7B, 0x6A, 0xB2, 0x62, 0x1D, 0xC2, 0x1B, 0x68, 0xE5, 0xC8, 0xB5, //
    0x3A, 0x05, 0x90, 0x00, 0xE8, 0xA8, 0x10, 0x3D, 0xE2, 0xEC, 0xF0, 0x0C, 0xB2, 0xED, 0x4F, 0x6D, //
  ]);

  static final Uint8List _outro = Uint8List.fromList(const [
    0xD6, 0xC0, 0x1C, 0x59, 0x8B, 0xC8, 0xB8, 0xCB, 0x46, 0xE1, 0x53, 0xFC, 0x82, 0x8C, 0x75, 0x75, //
    0x13, 0xE0, 0x45, 0xDF, 0x32, 0x69, 0x3C, 0x75, 0xF0, 0x59, 0xF8, 0xD9, 0xA2, 0x5F, 0xB2, 0x17, //
    0xE0, 0x80, 0x52, 0xDB, 0xEA, 0x89, 0x73, 0x99, 0x75, 0x79, 0xAF, 0xCB, 0x2E, 0x80, 0x07, 0xE6, //
    0xF1, 0x26, 0xE0, 0x03, 0x0A, 0xE6, 0x6F, 0xF6, 0x41, 0xBF, 0x7E, 0x59, 0xC2, 0xAE, 0x55, 0xFD, //
  ]);

  /// Xorpad estático (0x7F bytes efectivos).
  static const List<int> _xorpad = [
    0xA0, 0x92, 0xD1, 0x06, 0x07, 0xDB, 0x32, 0xA1, 0xAE, 0x01, 0xF5, 0xC5, 0x1E, 0x84, 0x4F, 0xE3, //
    0x53, 0xCA, 0x37, 0xF4, 0xA7, 0xB0, 0x4D, 0xA0, 0x18, 0xB7, 0xC2, 0x97, 0xDA, 0x5F, 0x53, 0x2B, //
    0x75, 0xFA, 0x48, 0x16, 0xF8, 0xD4, 0x8A, 0x6F, 0x61, 0x05, 0xF4, 0xE2, 0xFD, 0x04, 0xB5, 0xA3, //
    0x0F, 0xFC, 0x44, 0x92, 0xCB, 0x32, 0xE6, 0x1B, 0xB9, 0xB1, 0x2E, 0x01, 0xB0, 0x56, 0x53, 0x36, //
    0xD2, 0xD1, 0x50, 0x3D, 0xDE, 0x5B, 0x2E, 0x0E, 0x52, 0xFD, 0xDF, 0x2F, 0x7B, 0xCA, 0x63, 0x50, //
    0xA4, 0x67, 0x5D, 0x23, 0x17, 0xC0, 0x52, 0xE1, 0xA6, 0x30, 0x7C, 0x2B, 0xB6, 0x70, 0x36, 0x5B, //
    0x2A, 0x27, 0x69, 0x33, 0xF5, 0x63, 0x7B, 0x36, 0x3F, 0x26, 0x9B, 0xA3, 0xED, 0x7A, 0x53, 0x00, //
    0xA4, 0x48, 0xB3, 0x50, 0x9E, 0x14, 0xA0, 0x52, 0xDE, 0x7E, 0x10, 0x2B, 0x1B, 0x77, 0x6E, //
  ];

  /// Aplica (o revierte, es simétrico) el xorpad estático in situ.
  static void cryptStaticXorpad(Uint8List data, [int length = -1]) {
    final n = length < 0 ? data.length : length;
    const size = 0x7F;
    for (var i = 0; i < n; i++) {
      data[i] ^= _xorpad[i % size];
    }
  }

  static Uint8List _computeHash(Uint8List payload) {
    final out = AccumulatorSink<Digest>();
    final input = sha256.startChunkedConversion(out);
    input.add(_intro);
    input.add(payload);
    input.add(_outro);
    input.close();
    return Uint8List.fromList(out.events.single.bytes);
  }

  /// `true` si los últimos 0x20 bytes son el SHA-256 válido del resto.
  static bool isHashValid(Uint8List data) {
    if (data.length <= hashSize) return false;
    final payload = data.view(0, data.length - hashSize);
    final computed = _computeHash(payload);
    for (var i = 0; i < hashSize; i++) {
      if (computed[i] != data[data.length - hashSize + i]) return false;
    }
    return true;
  }

  /// Descifra el save (no modifica [data]) y devuelve sus bloques.
  ///
  /// Se asume que [isHashValid] ya fue comprobado.
  static List<SCBlock> decrypt(Uint8List data) {
    final payload = data.copyRange(0, data.length - hashSize);
    cryptStaticXorpad(payload);
    return SCBlock.readAll(payload);
  }

  /// Serializa y cifra [blocks] generando un save válido con hash.
  static Uint8List encrypt(List<SCBlock> blocks) {
    final builder = BytesBuilder(copy: false);
    for (final b in blocks) {
      builder.add(b.serialize());
    }
    final payload = builder.takeBytes();
    cryptStaticXorpad(payload);
    final hash = _computeHash(payload);
    final result = Uint8List(payload.length + hashSize)
      ..setRange(0, payload.length, payload)
      ..setRange(payload.length, payload.length + hashSize, hash);
    return result;
  }
}

/// Sink mínimo para recoger el digest del hash por fragmentos.
class AccumulatorSink<T> implements Sink<T> {
  final List<T> events = [];

  @override
  void add(T data) => events.add(data);

  @override
  void close() {}
}
